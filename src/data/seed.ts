function item(
  code: string,
  id: string,
  name: string,
  category: string,
  unitId: string,
  minStock = 1,
) {
  return {
    id,
    code,
    name,
    kind: "raw" as const,
    category,
    baseUnitId: unitId,
    purchaseUnitId: unitId,
    minStock,
    active: true,
  };
}

function buy(
  batchNo: string,
  date: string,
  supplier: string,
  itemId: string,
  qty: number,
  unitId: string,
  rate: number,
  createdBy: string,
  taxPct = 0,
  freight = 0,
) {
  return {
    id: batchNo,
    batchNo,
    date,
    supplier,
    itemId,
    qty,
    unitId,
    rate,
    taxPct,
    freight,
    createdBy,
  };
}

function line(
  source: "item" | "recipe",
  refId: string,
  qty: number,
  unitId: string,
) {
  return {
    id: `${source}-${refId}-${qty}-${unitId}`,
    source,
    refId,
    qty,
    unitId,
  };
}
